/*
 * load_level — ASM: Load_Level (7888)
 *
 * Structure follows the original 6502 code faithfully:
 *   - goto labels mirror ASM branch targets
 *   - Temp, Counter, Block_X, Block_Y, ScrBuffer_Pos are global zero-page vars
 *   - LowStrPtr_Byte / HighStrPtr_Byte are replaced by a local C pointer (level_ptr)
 *     because the host is 64-bit; the read `(LowStrPtr_Byte),Y` becomes level_ptr[y]
 *   - Inc_Ptr_on_A $5B is replaced by level_ptr += LEVEL_SIZE
 */
void load_level(uint8_t level_num) {
    const uint8_t *level_ptr;
    uint8_t        tsa;
    uint8_t        y;

    /* ---- CMP #$FF / BNE @normalLevell ------------------------------------ */
    if (level_num == 0xFF) {
        level_num = 0x24; /* LDA #$24 — demo level index */
        goto begin;
    }

    /* @normalLevell: */
    /* CMP #$24 / BCC @begin — if level_num < 0x24, already valid */
    if (level_num < LEVEL_MAX) goto begin;

    /* SEC / SBC #$23 — wrap back towards level 1 */
    level_num -= 0x23;

begin: /* ASM: @begin */
    /* STA Temp */
    Temp = level_num;

    /* LDA/STA HighPtr_Byte + LDA/STA LowPtr_Byte — point ptr to Level_Data */
    level_ptr = Level_Data;

    /* ASM: @_: DEC Temp / BEQ @__ / JSR Inc_Ptr_on_A #$5B / JMP @_ */
at_: /* ASM: @_ */
    Temp--;
    if (Temp == 0) goto at__;
    level_ptr += LEVEL_SIZE;
    goto at_;

at__: /* ASM: @__ */
    /* LDA #0 / STA Counter */
    Counter = 0;
    /* LDA/STA LowStrPtr_Byte, HighStrPtr_Byte — stored in level_ptr */
    /* LDA #$10 / STA Block_Y */
    Block_Y = 0x10;

    /* @loop: JSR NMI_Wait */
loop: /* ASM: @loop */
    nmi_wait();

    /* LDA #$10 / STA Block_X */
    Block_X = 0x10;

    /* @loop_2: */
loop_2: /* ASM: @loop_2 */
    /* LDA Counter / LSR A / TAY */
    y = Counter >> 1;

    /* LDA Counter / AND #1 / BEQ @shr4 */
    if (Counter & 1) {
        /* LDA (LowStrPtr_Byte),Y / AND #$F */
        tsa = level_ptr[y] & 0x0F;
        /* JMP @drawTsa */
        goto drawTsa;
    }

    /* @shr4: LDA (LowStrPtr_Byte),Y / LSR A *4 */
    tsa = level_ptr[y] >> 4;

    /* @drawTsa: LDX Block_X / LDY Block_Y / JSR Draw_TSABlock */
drawTsa: /* ASM: @drawTsa */
    draw_tsa_block(tsa);

    /* LDA #0 / STA ScrBuffer_Pos */
    ScrBuffer_Pos = 0;

    /* INC Counter */
    Counter++;

    /* LDA Block_X / CLC / ADC #$10 / STA Block_X / CMP #$E0 / BNE @loop_2 */
    Block_X += 0x10;
    if (Block_X != 0xE0) goto loop_2;

    /* INC Counter  (skip 14th nibble slot — padding in level data) */
    Counter++;

    /* LDA Block_Y / CLC / ADC #$10 / STA Block_Y / CMP #$E0 / BNE @loop */
    Block_Y += 0x10;
    if (Block_Y != 0xE0) goto loop;

    /* RTS */
}
